function normalizeFieldKey(key: string): string {
  return key.trim();
}

function getFallbackFieldLabel(key: string): string {
  const normalized = normalizeFieldKey(key);
  if (MO_FIELD_LABELS_ZH_CN[normalized]) return MO_FIELD_LABELS_ZH_CN[normalized];

  for (const patternDoc of FIELD_PATTERN_DOCS_ZH_CN) {
    const matched = normalized.match(patternDoc.pattern);
    if (matched) {
      const target = matched[1] ?? '';
      const targetLabel = MO_FIELD_LABELS_ZH_CN[target] || target;
      return patternDoc.zhNameTemplate.replace('{target}', targetLabel);
    }
  }

  return normalized;
}

export function resolveFieldDocZhCN(key: string): ResolvedFieldDocZhCN {
  const normalized = normalizeFieldKey(key);
  const exactDoc = MO_FIELD_DOCS_ZH_CN[normalized];
  if (exactDoc) {
    return { ...exactDoc, exact: true };
  }

  for (const patternDoc of FIELD_PATTERN_DOCS_ZH_CN) {
    const matched = normalized.match(patternDoc.pattern);
    if (matched) {
      const target = matched[1] ?? '';
      const targetLabel = MO_FIELD_LABELS_ZH_CN[target] || target;
      return {
        key: normalized,
        zhName: patternDoc.zhNameTemplate.replace('{target}', targetLabel),
        category: patternDoc.category,
        description: patternDoc.description,
        valueDirection: patternDoc.valueDirection,
        suggestedChange: patternDoc.suggestedChange,
        risk: patternDoc.risk,
        valueKind: patternDoc.valueKind,
        examples: [],
        exact: false,
      };
    }
  }

  return {
    key: normalized,
    zhName: getFallbackFieldLabel(normalized),
    category: '未分类字段',
    description: '该字段暂无详细说明。已提供中文化字段名兜底；修改前建议结合所在段落类型和原值判断。',
    valueDirection: '未知。',
    suggestedChange: '不确定用途时不要改，或者先小幅修改并备份原文件。',
    risk: 'unknown',
    valueKind: 'mixed',
    examples: [],
    exact: false,
  };
}

export function getFieldLabelZhCN(key: string): string {
  return resolveFieldDocZhCN(key).zhName;
}

export function getFieldSearchTextZhCN(key: string): string {
  const doc = resolveFieldDocZhCN(key);
  return [doc.key, doc.zhName, doc.category, doc.description, doc.valueDirection, doc.suggestedChange]
    .filter(Boolean)
    .join(' ');
}

function parseNumberLike(value: string): number | null {
  const trimmed = value.trim().replace('%', '');
  if (!trimmed) return null;
  const n = Number(trimmed);
  return isFinite(n) ? n : null;
}

function isYes(value: string): boolean {
  return /^(yes|true|1)$/i.test(value.trim());
}

function isNo(value: string): boolean {
  return /^(no|false|0)$/i.test(value.trim());
}

export function analyzeFieldValueZhCN(key: string, rawValue: string): FieldValueAnalysisZhCN | null {
  const normalized = normalizeFieldKey(key);
  const value = rawValue.trim();
  const num = parseNumberLike(value);

  if (normalized === 'Speed' && num !== null) {
    if (num <= 2) return { label: '极慢', tone: 'warning', description: '通常属于非常笨重或特殊对象。' };
    if (num === 3) return { label: '很慢', tone: 'neutral', description: '常见于重型攻城单位。' };
    if (num <= 5) return { label: '常规速度', tone: 'good', description: '多数载具的舒适速度区间。' };
    if (num <= 8) return { label: '较快', tone: 'good', description: '机动性已经比较强。' };
    return { label: '非常快', tone: 'warning', description: '可能明显改变手感和平衡。' };
  }

  if ((normalized === 'ROT' || normalized === 'TurretROT') && num !== null) {
    if (num <= 1) return { label: '转向很笨', tone: 'warning', description: '转身或炮塔跟枪会很慢。' };
    if (num <= 3) return { label: '重型转向', tone: 'neutral', description: '重型单位常见。' };
    if (num <= 5) return { label: '常规转向', tone: 'good', description: '手感较正常。' };
    return { label: '灵活转向', tone: 'warning', description: '过高可能让重型单位显得不自然。' };
  }

  if (normalized === 'ROF' && num !== null) {
    if (num <= 10) return { label: '极高射速', tone: 'danger', description: '开火间隔极短，可能过强或造成性能压力。' };
    if (num <= 30) return { label: '高射速', tone: 'warning', description: '输出频率很高。' };
    if (num <= 80) return { label: '常规射速', tone: 'good', description: '多数武器的正常区间。' };
    if (num <= 150) return { label: '慢射速', tone: 'neutral', description: '重炮或高伤武器常见。' };
    return { label: '很慢', tone: 'warning', description: '攻城炮、超重武器常见。' };
  }

  if (normalized === 'Damage' && num !== null) {
    if (num <= 20) return { label: '低伤害', tone: 'neutral', description: '常见于机枪、小型碎片或多段伤害。' };
    if (num <= 60) return { label: '中低伤害', tone: 'neutral', description: '轻武器或快速武器常见。' };
    if (num <= 120) return { label: '中高伤害', tone: 'good', description: '主战武器常见。' };
    if (num <= 250) return { label: '高伤害', tone: 'warning', description: '重炮或高爆武器常见。' };
    return { label: '超高伤害', tone: 'danger', description: '超武、死亡武器或特殊武器级别。' };
  }

  if (normalized === 'Range' && num !== null) {
    if (num <= 4) return { label: '近距离', tone: 'neutral', description: '近战或短程武器。' };
    if (num <= 7) return { label: '常规射程', tone: 'good', description: '普通交战距离。' };
    if (num <= 11) return { label: '远射程', tone: 'warning', description: '远程单位常见。' };
    if (num <= 15) return { label: '超远射程', tone: 'warning', description: '攻城或特殊单位常见。' };
    return { label: '攻城级射程', tone: 'danger', description: '非常远，容易破坏地图和平衡。' };
  }

  if (normalized === 'CellSpread' && num !== null) {
    if (num === 0) return { label: '无明显溅射', tone: 'neutral', description: '基本单体伤害。' };
    if (num <= 0.5) return { label: '小范围溅射', tone: 'good', description: '轻微范围伤害。' };
    if (num <= 1.5) return { label: '中等溅射', tone: 'warning', description: '范围伤害明显。' };
    if (num <= 3) return { label: '大范围溅射', tone: 'warning', description: '对集群目标很强。' };
    return { label: '超大范围', tone: 'danger', description: '容易过强，也可能影响性能。' };
  }

  if (/^(Versus\.|ProneDamage|PercentAtMax)/.test(normalized) && num !== null) {
    if (num === 0) return { label: '完全无效', tone: 'danger', description: '对该目标或边缘范围不造成伤害。' };
    if (num <= 25) return { label: '刮痧', tone: 'warning', description: '效果很弱。' };
    if (num <= 75) return { label: '偏弱', tone: 'neutral', description: '低于正常倍率。' };
    if (num <= 125) return { label: '正常', tone: 'good', description: '接近标准倍率。' };
    if (num <= 200) return { label: '克制', tone: 'warning', description: '对目标有明显克制。' };
    return { label: '强克制', tone: 'danger', description: '伤害倍率非常高。' };
  }

  if (['SelfHealing', 'ImmuneToPsionics', 'ImmuneToEMP', 'OpenTopped', 'OmniCrusher'].indexOf(normalized) >= 0) {
    if (isYes(value)) return { label: '已启用', tone: 'warning', description: '该效果通常会增强对象或改变克制关系。' };
    if (isNo(value)) return { label: '未启用', tone: 'neutral', description: '该效果当前未启用。' };
  }

  return null;
}
